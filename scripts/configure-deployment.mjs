import {decode64} from '../server/web-push.mjs';
import {readFile,writeFile} from 'node:fs/promises';
const filename=new URL('../wrangler.jsonc',import.meta.url);
const config=JSON.parse(await readFile(filename,'utf8'));
const id=process.env.WILLFIT_D1_ID||config.d1_databases[0].database_id;
if(!/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i.test(id))throw new Error('Set the GitHub repository variable WILLFIT_D1_ID to your Cloudflare D1 database ID before deploying.');
config.d1_databases[0].database_id=id;
const pushKey=process.env.WILLFIT_VAPID_PUBLIC_KEY||config.vars?.VAPID_PUBLIC_KEY;
if(pushKey&&decode64(pushKey).length!==65)throw new Error('Set the GitHub repository variable WILLFIT_VAPID_PUBLIC_KEY to the public key generated by npm run push:keys. The private key belongs only in the Cloudflare VAPID_PRIVATE_KEY secret.');
if(pushKey)config.vars={...config.vars,VAPID_PUBLIC_KEY:pushKey};
await writeFile(filename,JSON.stringify(config,null,2)+'\n');
